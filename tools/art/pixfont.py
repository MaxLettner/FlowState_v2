HEIGHT = 7


def glyph_width(c):
    return len(FONT[c][0])


def text_width(text, scale=1):
    return (sum(glyph_width(c) for c in text) + len(text) - 1) * scale


def text_cells(text, scale=1):
    """Ink pixels of the text with its top-left at (0, 0)."""
    cells = set()
    x = 0
    for c in text:
        for gy, row in enumerate(FONT[c]):
            for gx, ch in enumerate(row):
                if ch == '#':
                    for sx in range(scale):
                        for sy in range(scale):
                            cells.add((x + gx * scale + sx, gy * scale + sy))
        x += (glyph_width(c) + 1) * scale
    return cells
